          <h2 id="section-steps">۴. مراحل گام‌به‌گام آزمون و دریافت کارت هوشمند مهارت در ماهریار</h2>
          <p>
            آموزشگاه ماهریار به عنوان مجری رسمی سازمان، تمامی هماهنگی‌های آزمون کارآموزان را بر عهده دارد:
          </p>
          <ol>
            <li><strong>شرکت در دوره کارگاهی:</strong> گذراندن ساعات تئوری و کارگاهی در کارگاه‌های مجهز شعب مرتضوی یا اسکندری (یا دوره‌های تعاملی مجازی).</li>
            <li><strong>ثبت‌نام در پورتال سازمان فنی و حرفه‌ای:</strong> ارسال مدارک هویتی توسط دپارتمان اداری ماهریار و صدور کارت ورود به جلسه آزمون.</li>
            <li><strong>آزمون هماهنگ کتبی (تستی):</strong> آزمون چهارگزینه‌ای آنلاین در مراکز سنجش الکترونیکی سازمان (کسب حداقل نمره ۵۰ از ۱۰۰).</li>
            <li><strong>آزمون عملی در کارگاه ماهریار:</strong> ارزیابی پروژه عملی و شایستگی کارآموز توسط بازرس و اگزمینر رسمی سازمان (کسب حداقل نمره ۷۰ از ۱۰۰).</li>
            <li><strong>صدور گواهینامه الکترونیکی:</strong> ثبت نمره نهایی در سامانه و دریافت گواهینامه با کد شناسایی منحصر‌به‌فرد.</li>
          </ol>

          <h2 id="section-translation">۵. نحوه ترجمه رسمی با تاییدات قوه قضائیه و وزارت امور خارجه</h2>
          <p>
            برای ترجمه رسمی مدرک خود، نیازی به مراجعات پیچیده اداری نیست. فرآیند به شکل زیر انجام می‌پذیرد:
          </p>
          <ul>
            <li>ابتدا به سامانه استعلام گواهینامه سازمان فنی و حرفه‌ای (certificate.portaltvto.com) مراجعه کرده و پرینت گواهینامه مهارت دارای بارکد را تهیه فرمایید.</li>
            <li>پرینت گواهینامه را به یک دارالترجمه رسمی مورد تایید دادگستری ارائه دهید. دارالترجمه با وارد کردن کد ملی و کد شناسایی در پورتال، اصالت مدرک را تایید می‌کند.</li>
            <li>مترجم رسمی دادگستری متن گواهینامه شامل نام مهارت، ساعات آموزشی و کد بین‌المللی ISCO را به انگلیسی (یا زبان کشور مقصد) ترجمه نموده و بر روی سربرگ قوه قضائیه پلمپ می‌کند.</li>
            <li>بسته به نیاز سفارت، مهر تایید اداره کل اسناد و امور مترجمان قوه قضائیه و وزارت امور خارجه جمهوری اسلامی ایران بر روی ترجمه درج می‌گردد.</li>
          </ul>

          <h2 id="section-countries">۶. کدام کشورها مدرک فنی و حرفه‌ای ایران را پذیرش می‌کنند؟</h2>
          <p>
            با توجه به اینکه آموزش‌های فنی و حرفه‌ای مبتنی بر استانداردهای جهانی است، کشورهای زیر بیشترین استقبال را از فارغ‌التحصیلان فنی و حرفه‌ای با سابقه کار دارند:
          </p>
          <ul>
            <li><strong>آلمان:</strong> به ویژه در رشته‌های برنامه‌نویسی پایتون، مهندسی، خیاطی و برق صنعتی از طریق ویزای Chancenkarte.</li>
            <li><strong>کانادا:</strong> در برنامه‌های مهاجرت استانی (PNP) و برنامه نیروهای متخصص ماهر (Federal Skilled Trades Program).</li>
            <li><strong>استرالیا:</strong> در لیست مشاغل مورد نیاز مهارتی (MLTSSL و STSOL).</li>
            <li><strong>کشورهای حوزه خلیج فارس (امارات، عمان، قطر):</strong> استخدام در شرکت‌های پیمانکاری، آتلیه‌های طراحی لباس و پروژه‌های اتوماسیون.</li>
          </ul>

